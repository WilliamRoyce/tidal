    def test_synthetic_all_rows_close(self) -> None:
        spec = _synthetic_velc_spec()
        grid = GridInfo(bounds=((0.0, 2 * np.pi),), shape=(24,), periodic=(True,))
        params = {"alpha": 0.5}
